interface PlacedActivity {
  uid: string
  activity: Activity
}

async function buildProjectZip(projectName: string, plan: PlacedActivity[]) {
  const zip = new JSZip()
  const rootName = slugify(projectName)
  const root = zip.folder(rootName)!
  const date = new Date().toISOString().split('T')[0]
  const activities = plan.map((p) => p.activity)

  // README at root
  root.file('README.md', buildReadme(projectName, date, activities, true))

  // Each activity gets its own folder with SKILL.md
  plan.forEach((item) => {
    const { activity } = item
    const skillFolder = root.folder(activity.skillName)!
    const content = activity.availability === 'skill' && activity.skillFileContent
      ? activity.skillFileContent
      : [
          `# ${activity.name}`,
          ``,
          `**Phase:** ${activity.phaseNumber} — ${activity.phase}  `,
          `**Autonomy mode:** ${activity.mode}  `,
          `**Last updated:** ${activity.lastUpdated}`,
          ``,
          `---`,
          ``,
          `## Prompt`,
          ``,
          `> Copy the prompt below, fill in the \`[bracketed placeholders]\`, and paste into Devin's chat.`,
          ``,
          `\`\`\``,
          activity.promptContent ?? `_Prompt content coming soon._`,
          `\`\`\``,
          ``,
          `---`,
          ``,
          `## Designer's Responsibility`,
          ``,
          `⚠️ ${activity.responsibility}`,
        ].join('\n')
    skillFolder.file('SKILL.md', content)
  })

  const blob = await zip.generateAsync({ type: 'blob' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = `${rootName}.zip`
  a.click()
  URL.revokeObjectURL(url)
}

