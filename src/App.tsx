function CodeBlock({ code }: { code: string }) {
  const [copied, setCopied] = useState(false)
  const copy = () => {
    navigator.clipboard.writeText(code)
    setCopied(true)
    setTimeout(() => setCopied(false), 2000)
  }
  return (
    <div className="relative group rounded-xl overflow-hidden bg-slate-950 border border-slate-800">
      <pre className="text-xs text-slate-300 font-mono px-5 py-4 overflow-x-auto leading-relaxed">{code}</pre>
      <button
        onClick={copy}
        className="absolute top-3 right-3 px-2.5 py-1 rounded-md text-[10px] font-semibold transition-all bg-slate-800 text-slate-400 hover:bg-slate-700 hover:text-white"
      >
        {copied ? '✓ Copied' : 'Copy'}
      </button>
    </div>
  )
}

