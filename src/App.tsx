async function downloadAllSkills() {
  const skillActivities = ALL_ACTIVITIES.filter((a) => a.availability === 'skill')
  const zip = new JSZip()
  const rootName = 'cypher_std_skill'
  const root = zip.folder(rootName)!
  const date = new Date().toISOString().split('T')[0]

  root.file('README.md', buildReadme('Cypher Skill Collection', date, skillActivities, false))

  skillActivities.forEach((activity) => {
    const skillFolder = root.folder(activity.skillName)!
    skillFolder.file('SKILL.md', activity.skillFileContent ?? `# ${activity.skillName}\n\n_Skill file coming soon._\n`)
  })

  const blob = await zip.generateAsync({ type: 'blob' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = `${rootName}.zip`
  a.click()
  URL.revokeObjectURL(url)
}

