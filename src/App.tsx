const MODE_STYLES: Record<Mode, { bg: string; text: string; dot: string }> = {
  'Human-led': { bg: 'bg-amber-50', text: 'text-amber-800', dot: 'bg-amber-400' },
  'AI-assisted': { bg: 'bg-teal-50', text: 'text-teal-800', dot: 'bg-teal-500' },
  'AI-driven': { bg: 'bg-violet-50', text: 'text-violet-800', dot: 'bg-violet-500' },
  Mixed: { bg: 'bg-slate-100', text: 'text-slate-600', dot: 'bg-slate-400' },
}

const AVAIL_STYLES: Record<Availability, { bg: string; text: string; border: string; dot: string; label: string }> = {
  skill: {
    bg: '#f0fdf4', text: '#166534', border: '#bbf7d0', dot: '#22c55e',
    label: 'Skill file',
  },
  prompt: {
    bg: '#fffbeb', text: '#92400e', border: '#fde68a', dot: '#f59e0b',
    label: 'Prompt only',
  },
}

function AvailabilityChip({ availability }: { availability: Availability }) {
  const s = AVAIL_STYLES[availability] ?? { bg: '#f8fafc', text: '#64748b', border: '#e2e8f0', dot: '#94a3b8', label: String(availability) }
  return (
    <span
      className="inline-flex items-center gap-1.5 px-2 py-0.5 rounded-full text-[10px] font-semibold"
      style={{ background: s.bg, color: s.text, border: `1px solid ${s.border}` }}
    >
      <span className="w-1.5 h-1.5 rounded-full flex-shrink-0" style={{ background: s.dot }} />
      {s.label}
    </span>
  )
}

function ModeBadge({ mode, size = 'sm' }: { mode: Mode; size?: 'xs' | 'sm' }) {
  const s = MODE_STYLES[mode]
  return (
    <span
      className={`inline-flex items-center gap-1.5 rounded-full font-medium ${s.bg} ${s.text} ${
        size === 'xs' ? 'px-2 py-0.5 text-[10px]' : 'px-2.5 py-1 text-xs'
      }`}
    >
      <span className={`rounded-full flex-shrink-0 ${s.dot} ${size === 'xs' ? 'w-1 h-1' : 'w-1.5 h-1.5'}`} />
      {mode}
    </span>
  )
}

